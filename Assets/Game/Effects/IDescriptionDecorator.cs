namespace Game.Effects
{
    /// <summary>
    /// 给卡牌 / 药水描述**上色**用的钩子。由表现层实现，逻辑层只负责在正确的位置回调它。
    ///
    /// ★★ 为什么这件事必须做成一个接口，而不是让 UI 拿到成品字符串再去改：
    ///    描述是 <c>"造成 {0} 点伤害，施加 {1} 层易伤。"</c> 这种模板，
    ///    <c>{N}</c> 在 <see cref="EffectDescription.Format"/> 里被换成第 N 个效果算出来的数字。
    ///    「哪一段是数字」「那个数字是伤害还是护甲」这两件事**只有替换发生的那一刻知道**——
    ///    成品字符串 <c>"造成 9 点伤害"</c> 里的 9 与 "9 点" 中的任何字符没有区别，
    ///    UI 想染色就只能去正则匹配数字，而那会在
    ///    「造成 2 次 9 点伤害」「获得 9 点护甲」「抽 2 张牌」之间全部失效。
    ///
    ///    换句话说：**结构信息在格式化之后就永久丢失了**，只能在丢失之前取。
    ///    这与铁律 29（tooltip 词条从数据推导、不做文案子串匹配）是同一条原则的另一个面。
    ///
    /// ★ 接口里刻意只有 <c>string</c>，不出现任何 UnityEngine / TMP 类型：
    ///   逻辑层不需要知道「上色」在表现层是靠 TMP 的富文本标签实现的。
    ///   自动模拟器、战斗日志、Editor 的卡表预览一律传 null，
    ///   拿到的就是**和现在一模一样的纯文本**。
    /// </summary>
    public interface IDescriptionDecorator
    {
        /// <summary>
        /// 装饰模板本身（<c>{N}</c> 还没被替换掉）。
        /// 表现层在这里给「易伤」「消耗」这类**写死在文案里**的词条名上色。
        ///
        /// ★ 在替换之前做，是为了让插进去的标记不可能命中占位符，
        ///   也不可能命中替换出来的数字。顺序反过来的话，一个颜色码里的
        ///   十六进制字母就可能被当成词条名匹配到。
        /// </summary>
        string DecorateTemplate(string template);

        /// <summary>
        /// 装饰一个 <c>{N}</c> 替换出来的值。<paramref name="effect"/> 是产出它的那个效果，
        /// 表现层据此决定颜色（伤害红、护甲蓝、状态按增益/减益……）。
        /// </summary>
        string DecorateValue(string value, CardEffect effect);
    }
}
